/** 覆盖矩阵页生成:从 dist 构建产物读规则元数据与评测用例,渲染 zh/en 两页。
 *  矩阵是生成物不是手抄物——规则的 threats 变了,重跑脚本页面就变。 */
import { writeFile } from 'node:fs/promises'
import {
  THREAT_CATALOG_VERSION, coverageMatrix, dataCases, ioCases,
  referenceDataGuard, referenceIoGuard, renderCoverageMarkdown,
} from '../dist/eval/index.js'

const rules = [...referenceIoGuard().rules(), ...referenceDataGuard().rules()]
const cases = [...ioCases(), ...dataCases()]
const matrix = coverageMatrix(rules, cases)

const zh = `---
title: OWASP 覆盖矩阵
---

# OWASP 覆盖矩阵

> 本页由 \`pnpm gen:coverage\` 从规则的 \`threats\` 元数据与评测用例生成,不手工维护。
> 名录版本 ${THREAT_CATALOG_VERSION}(OWASP LLM Top 10 2026 · Agentic/ASI Top 10 2026)。
> 「攻击用例验证」列出内置数据集中真实打到该威胁的攻击用例——声称覆盖与验证过覆盖是两回事。

${renderCoverageMarkdown(matrix, 'zh')}
`

const en = `---
title: OWASP Coverage Matrix
---

# OWASP coverage matrix

> Generated by \`pnpm gen:coverage\` from rule \`threats\` metadata and eval cases — never hand-edited.
> Catalog version ${THREAT_CATALOG_VERSION} (OWASP LLM Top 10 2026 · Agentic/ASI Top 10 2026).
> "Verified by attack cases" lists built-in dataset attacks that actually hit the threat — claiming coverage and having verified it are different things.

${renderCoverageMarkdown(matrix, 'en')}
`

await writeFile(new URL('../docs/coverage.md', import.meta.url), zh)
await writeFile(new URL('../docs/en/coverage.md', import.meta.url), en)
console.log(`coverage matrix written (catalog ${THREAT_CATALOG_VERSION}, ${matrix.rows.length} threats, ${matrix.uncovered.length} uncovered)`)
